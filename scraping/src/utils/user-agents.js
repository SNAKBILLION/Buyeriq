let lastIndex = -1;

/**
 * Get a random user agent (never the same as the last one)
 */
export function getRandomUserAgent() {
  let index;
  do {
    index = Math.floor(Math.random() * USER_AGENTS.length);
  } while (index === lastIndex && USER_AGENTS.length > 1);
  lastIndex = index;
  return USER_AGENTS[index];
}

/**
 * Get browser-like headers for a given domain
 */
export function getBrowserHeaders(domain = '') {
  return {
    'User-Agent': getRandomUserAgent(),
    'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8',
    'Accept-Language': 'en-US,en;q=0.9',
    'Accept-Encoding': 'gzip, deflate, br',
    'DNT': '1',
    'Connection': 'keep-alive',
    'Upgrade-Insecure-Requests': '1',
    'Sec-Fetch-Dest': 'document',
    'Sec-Fetch-Mode': 'navigate',
    'Sec-Fetch-Site': 'none',
    'Sec-Fetch-User': '?1',
    'Cache-Control': 'max-age=0',
    ...(domain && { 'Referer': `https://www.google.com/search?q=${encodeURIComponent(domain)}` }),
  };
}

export default { getRandomUserAgent, getBrowserHeaders };
